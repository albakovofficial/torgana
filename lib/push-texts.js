const BY_KEY = new Map(CATALOG.map((c) => [c.key, c]));
const holes = (s) => [...String(s).matchAll(/\{([^{}]+)\}/g)].map((m) => m[1]);
// Подстановки, которые понимает уведомление: из его текста по умолчанию.
const varsOf = (c) => [...new Set([...holes(c.title), ...holes(c.body)])];
const LIMIT = { title: 120, body: 300 };

module.exports = function pushTexts({ db }) {
  const custom = () => { try { return JSON.parse(db.setting('push_texts') || '{}'); } catch { return {}; } };
  const fill = (tpl, vars) => String(tpl).replace(/\{([^{}]+)\}/g, (_, k) => (vars[k] === undefined || vars[k] === null ? '' : String(vars[k])))
    .replace(/\s+([.,:;])/g, '$1').replace(/\s{2,}/g, ' ').trim();
  // Готовые заголовок и текст: свой текст модератора, если есть, иначе по умолчанию.
  function render(key, vars = {}) {
    const c = BY_KEY.get(key);
    if (!c) throw new Error(`push: нет уведомления ${key}`);
    const own = custom()[key] || {};
    return { title: fill(own.title || c.title, vars).slice(0, 200), body: fill(own.body || c.body, vars).slice(0, 400) };
  }
  // Для редактора: всё сразу, со своими текстами и примером, как увидит человек.
  function list() {
    const own = custom();
    return CATALOG.map((c) => ({ key: c.key, group: c.group, admin: c.admin, name: c.name, defTitle: c.title, defBody: c.body,
      title: (own[c.key] || {}).title || '', body: (own[c.key] || {}).body || '', vars: varsOf(c), sample: render(c.key, S) }));
  }
  // Сохранить свой текст; пустые поля — вернуть текст по умолчанию. Подстановки — только те, что понимает уведомление.
  function save(key, { title = '', body = '' }) {
    const c = BY_KEY.get(key);
    if (!c) return { error: 'Нет такого уведомления' };
    const t = String(title).trim(); const b = String(body).trim();
    if (t.length > LIMIT.title) return { error: `Заголовок — не длиннее ${LIMIT.title} символов` };
    if (b.length > LIMIT.body) return { error: `Текст — не длиннее ${LIMIT.body} символов` };
    const ok = varsOf(c); const bad = [...holes(t), ...holes(b)].filter((v) => !ok.includes(v));
    if (bad.length) return { error: `Такой подстановки нет: {${bad[0]}}. Можно: ${ok.map((v) => `{${v}}`).join(', ') || 'без подстановок'}` };
    const all = custom();
    if ((!t || t === c.title) && (!b || b === c.body)) delete all[key];
    else all[key] = { title: t === c.title ? '' : t, body: b === c.body ? '' : b };
    db.saveSetting('push_texts', JSON.stringify(all));
    return { ok: true };
  }
  return { render, list, save, sample: (key) => render(key, S), get: (key) => BY_KEY.get(key), SAMPLES: S, CATALOG, USER_GROUPS, ADMIN_KINDS };
};
module.exports.CATALOG = CATALOG;
