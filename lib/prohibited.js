// Возвращает категории, на которые похоже объявление (пустой массив — всё в порядке).
function checkProhibited(title, description) {
  const text = norm(`${title} ${description}`);
  return PROHIBITED.filter((c) => c.re.some((r) => r.test(text))).map((c) => ({ id: c.id, title: c.title }));
}

